#!/usr/bin/env python3
#
# Generate manufactured solutions for the unstructured FCI test
#
# Same manufactured solutions as ../fci/mms.py. On unstructured grids the
# nodes of each poloidal plane are stored along x with nz = 1, so BOUT++'s
# index coordinates x and z are not geometric. The expressions are therefore
# written in terms of xu and zu, which data/BOUT.inp defines from the grid
# coordinates R and Z (input:grid_variables), so that xu and zu equal x and z
# of the structured test.

import warnings
from math import pi
from pathlib import Path

from boutdata.data import BoutOptionsFile
from boutdata.mms import diff, exprToStr, x, y, z
from boututils.boutwarnings import AlwaysWarning
from sympy import Expr, Symbol, cos, sin, sqrt

warnings.simplefilter("ignore", AlwaysWarning)

f = sin(y - z) + sin(y - 2 * z)
K = cos(z - y)

Lx = 0.1
Ly = 10.0
Lz = 1.0

Bt = 1.0
Bp = 0.05
Bpprime = 0.1

Bpx = Bp + (x - 0.5) * Lx * Bpprime  # Note: x in range [0,1]
B = sqrt(Bpx**2 + Bt**2)


def FCI_grad_par(f: Expr) -> Expr:
    return (Bt * diff(f, y) * 2.0 * pi / Ly + Bpx * diff(f, z) * 2.0 * pi / Lz) / B


def FCI_grad2_par2(f: Expr) -> Expr:
    return FCI_grad_par(FCI_grad_par(f))


def FCI_div_par(f: Expr) -> Expr:
    return Bpx * FCI_grad_par(f / Bpx)


def FCI_div_par_K_grad_par(f: Expr, K: Expr) -> Expr:
    return (K * FCI_grad2_par2(f)) + (FCI_div_par(K) * FCI_grad_par(f))


def FCI_Laplace_par(f: Expr) -> Expr:
    return FCI_div_par(FCI_grad_par(f))


def div_a_grad_pol(a: Expr, f: Expr) -> Expr:
    """Poloidal-plane divergence div_pol(a grad_pol f), with R = (x - 1/2) Lx
    and Z = z Lz / (2 pi), as computed by Div_a_Grad_perp_FCI_unstructured
    (rho_s0 = 1)."""
    dR = 1.0 / Lx
    dZ = 2.0 * pi / Lz
    return dR**2 * diff(a * diff(f, x), x) + dZ**2 * diff(a * diff(f, z), z)


############################################
# Equations solved

xu, zu = Symbol("xu"), Symbol("zu")

options = BoutOptionsFile("data/BOUT.inp")

for name, expr in (
    ("input_field", f),
    ("K", K),
    ("grad_par_solution", FCI_grad_par(f)),
    ("grad2_par2_solution", FCI_grad2_par2(f)),
    ("div_par_solution", FCI_div_par(f)),
    ("div_par_K_grad_par_solution", FCI_div_par_K_grad_par(f, K)),
    ("div_par_K_grad_par_mod_solution", FCI_div_par_K_grad_par(f, K)),
    ("div_par_K_grad_par_som_solution", FCI_div_par_K_grad_par(f, K)),
    ("laplace_par_solution", FCI_Laplace_par(f)),
    ("FV_div_par_mod_solution", FCI_div_par(f * K)),
    ("FV_div_par_fvv_solution", FCI_div_par(f * K * K)),
    ("FV_div_a_grad_perp_solution", div_a_grad_pol(K, f)),
    ("FV_div_a_grad_perp_upwind_solution", div_a_grad_pol(K, f)),
    # Z component of the flux vector -K grad_pol f returned as flow_zlow
    ("FV_div_a_grad_perp_flowZ_solution", -K * diff(f, z) * 2.0 * pi / Lz),
):
    expr_str = exprToStr(expr.subs({x: xu, z: zu}, simultaneous=True))
    print(f"{name} = {expr_str}")
    options[name] = expr_str

options.write("data/BOUT.inp", overwrite=True)


############################################
# Cylindrical case (zoidberg.unstructured.make_test_grid("bout_mms_cyl")):
# pure toroidal field, annulus R in [1, 2], periodic Z with Lz = 1. Only the
# perpendicular operator is checked; the other operators are not tested on
# this grid, so their solutions are set to zero.

Rs, Zs = Symbol("Rg"), Symbol("Zg")  # grid coordinates (gridvar:R, gridvar:Z)
f_cyl = sin(2 * pi * Rs) * cos(2 * pi * Zs)
K_cyl = 1.0 + 0.3 * cos(2 * pi * Rs)
dagp_cyl = diff(Rs * K_cyl * diff(f_cyl, Rs), Rs) / Rs + diff(
    K_cyl * diff(f_cyl, Zs), Zs
)

lines = [
    "# Generated by mms.py (cylindrical case): do not edit",
    "",
    "Rg = gridvar:R",
    "Zg = gridvar:Z",
    f"input_field = {exprToStr(f_cyl)}",
    f"K = {exprToStr(K_cyl)}",
]
for name in (
    "grad_par",
    "grad2_par2",
    "div_par",
    "div_par_K_grad_par",
    "div_par_K_grad_par_mod",
    "div_par_K_grad_par_som",
    "laplace_par",
    "FV_div_par_mod",
    "FV_div_par_fvv",
):
    lines.append(f"{name}_solution = 0  # not checked on the cylindrical grid")
lines += [
    f"FV_div_a_grad_perp_solution = {exprToStr(dagp_cyl)}",
    f"FV_div_a_grad_perp_upwind_solution = {exprToStr(dagp_cyl)}",
    f"FV_div_a_grad_perp_flowZ_solution = {exprToStr(-K_cyl * diff(f_cyl, Zs))}",
    "",
    "[mesh]",
    "file = fci.grid.nc  # MXG and MYG come from the grid",
    "",
    "[mesh:ddy]",
    "first = C2",
    "second = C2",
    "",
    "[mesh:paralleltransform]",
    "type = fci",
    "y_periodic = true",
    "z_periodic = true",
    "",
    "[mesh:paralleltransform:xzinterpolation]",
    "type = precomputed",
    "",
    "[input:grid_variables]",
    "R = field3d",
    "Z = field3d",
    "",
]
with open("data_cyl/BOUT.inp", "w") as out:
    out.write("\n".join(lines))


############################################
# Cylindrical case with a sheared field for the parallel operators
# (zoidberg.unstructured.make_test_grid("bout_mms_cyl_sheared")):
# B_phi = 1/R, B_Z = 0.1 + 0.1 (R - 1.5), annulus R in [1, 2], periodic Z
# (Lz = 1), y the toroidal angle. Checks that the parallel operators use the
# cylindrical metric (g_22 = (R |B| / B_phi)^2 at the nodes and the
# half-step points) and the physical volume.

ys = Symbol("y")
Bphi_s = 1 / Rs
BZ_s = 0.1 + 0.1 * (Rs - 1.5)
B_s = sqrt(Bphi_s**2 + BZ_s**2)


def cyl_grad_par(u: Expr) -> Expr:
    return Bphi_s / (Rs * B_s) * diff(u, ys) + BZ_s / B_s * diff(u, Zs)


def cyl_div_par_K_grad_par(u: Expr, k: Expr) -> Expr:
    # div(k b b.grad u) = B b.grad(k b.grad(u) / B), since div B = 0
    return B_s * cyl_grad_par(k * cyl_grad_par(u) / B_s)


f_cp = sin(2 * pi * Zs - ys) * sin(pi * (Rs - 1)) + 0.3 * cos(2 * pi * Zs)
K_cp = 1.0 + 0.3 * cos(2 * pi * Zs - ys)
solutions = {
    "grad_par": cyl_grad_par(f_cp),
    "div_par_K_grad_par_mod": cyl_div_par_K_grad_par(f_cp, K_cp),
    "div_par_K_grad_par_som": cyl_div_par_K_grad_par(f_cp, K_cp),
}
lines = [
    "# Generated by mms.py (cylindrical sheared case): do not edit",
    "",
    "Rg = gridvar:R",
    "Zg = gridvar:Z",
    f"input_field = {exprToStr(f_cp)}",
    f"K = {exprToStr(K_cp)}",
]
for name in (
    "grad_par",
    "grad2_par2",
    "div_par",
    "div_par_K_grad_par",
    "div_par_K_grad_par_mod",
    "div_par_K_grad_par_som",
    "laplace_par",
    "FV_div_par_mod",
    "FV_div_par_fvv",
    "FV_div_a_grad_perp",
    "FV_div_a_grad_perp_upwind",
    "FV_div_a_grad_perp_flowZ",
):
    if name in solutions:
        lines.append(f"{name}_solution = {exprToStr(solutions[name])}")
    else:
        lines.append(f"{name}_solution = 0  # not checked on this grid")
lines += [
    "",
    "[mesh]",
    "file = fci.grid.nc  # MXG and MYG come from the grid",
    "",
    "[mesh:ddy]",
    "first = C2",
    "second = C2",
    "",
    "[mesh:paralleltransform]",
    "type = fci",
    "y_periodic = true",
    "z_periodic = true",
    "",
    "[mesh:paralleltransform:xzinterpolation]",
    "type = precomputed",
    "",
    "[input:grid_variables]",
    "R = field3d",
    "Z = field3d",
    "",
]
Path("data_cyl_sheared").mkdir(exist_ok=True)
with open("data_cyl_sheared/BOUT.inp", "w") as out:
    out.write("\n".join(lines))
